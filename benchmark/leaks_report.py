"""The leak comparison as Markdown and LaTeX tables."""

from __future__ import annotations

from typing import Any

CARRIERS = (
    "page",
    "link",
    "metadata",
    "xmp",
    "form_field",
    "annotation",
    "bookmark",
    "embedded_file",
    "structure",
    "off_page",
)
"""Where a planted item can lie, in the order reports list them."""
INJECTED = ("structure", "off_page")
"""Carriers the benchmark documents do not plant; the comparison adds them."""

_TITLES = {
    "overlay": "black rectangle",
    "apply_redactions": "apply_redactions",
    "tool": "this tool",
}


def markdown(results: dict[str, Any]) -> str:
    """Render a comparison's results as Markdown."""
    methods: list[str] = results["methods"]
    totals = results["totals"]
    titles = [_TITLES[method] for method in methods]
    lines = [
        f"# Redaction leaks: anonymizer {results['tool_version']}",
        "",
        f"Run {results['created']} on {results['machine']['system']} "
        f"{results['machine']['machine']}, Python {results['machine']['python']}"
        + (f", commit `{results['git_commit'][:7]}`" if results.get("git_commit") else "")
        + f". {totals['documents']} documents, {totals['items']} planted items.",
        "",
        "Targets are the planted items (an oracle), so only the redaction method differs. "
        "Each copy is saved and read again; an item counts when its own carrier still holds "
        f"it, whole or as a word unique to it. Two items ({', '.join(results['injected'])}) "
        "are added to every document, for the carriers the benchmark does not plant.",
    ]
    if totals["unlocated"]:
        lines += [
            "",
            f"**{totals['unlocated']} planted items could not be placed** and are left by every "
            "method.",
        ]
    lines += ["", "## Items still extractable, per carrier", ""]
    lines += _table(["carrier", "planted", *titles], _carrier_rows(totals, methods, ratio=True))
    lines += ["", "## Documents and the leak check", ""]
    lines += _table(["", *titles], _summary_rows(totals, methods))
    layers = sorted(
        {layer for method in methods for layer in _method(totals, method)["leak_layers"]}
    )
    lines += ["", "## Leaks the leak check reports on each copy, by layer", ""]
    lines += _table(
        ["layer", *titles],
        [
            [
                layer,
                *(str(_method(totals, method)["leak_layers"].get(layer, 0)) for method in methods),
            ]
            for layer in layers
        ],
    )
    lines += ["", "## Per document, items still extractable", ""]
    lines += _table(
        ["document", "planted", *titles],
        [
            [
                name,
                str(document["summary"]["items"]),
                *(str(document["methods"][method]["extractable"]) for method in methods),
            ]
            for name, document in results["documents"].items()
        ],
    )
    return "\n".join(lines) + "\n"


def latex(results: dict[str, Any]) -> str:
    r"""Render the per-carrier table as LaTeX (booktabs), ready to `\input`."""
    methods: list[str] = results["methods"]
    totals = results["totals"]
    commit = (results.get("git_commit") or "unknown")[:10]
    caption = (
        "Planted items still extractable from the redacted file, by where they were planted: "
        "a black rectangle over the words, PyMuPDF \\texttt{apply\\_redactions} on the page "
        "text alone, and this tool. The targets are the planted items, so detection plays no "
        f"part; {totals['documents']} synthetic documents. \\texttt{{structure}} and "
        "\\texttt{off\\_page} are one injected item per document."
    )
    heads = ["Carrier", "Planted", "black rectangle", "\\texttt{apply\\_redactions}", "this tool"]
    lines = [
        f"% leaks: generated by `python -m benchmark leaks`, commit {commit}.",
        "% Requires \\usepackage{booktabs}.",
        "",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\small",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        " & ".join(heads) + " \\\\",
        "\\midrule",
    ]
    rows = _carrier_rows(totals, methods, ratio=False)
    lines += [" & ".join([_escape(row[0]), *row[1:]]) + " \\\\" for row in rows[:-1]]
    lines += [
        "\\midrule",
        " & ".join(["all", *rows[-1][1:]]) + " \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        f"\\caption{{{caption}}}",
        "\\label{tab:leaks}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def _carrier_rows(totals: dict[str, Any], methods: list[str], *, ratio: bool) -> list[list[str]]:
    """Rows of the per-carrier table, the last one the total."""
    planted = totals["items_by_carrier"]
    carriers = sorted(planted, key=_carrier_order)

    def cell(left: int, whole: int) -> str:
        return f"{left}/{whole}" if ratio else str(left)

    rows = [
        [
            carrier,
            str(planted[carrier]),
            *(
                cell(
                    _method(totals, method)["extractable_by_carrier"].get(carrier, 0),
                    planted[carrier],
                )
                for method in methods
            ),
        ]
        for carrier in carriers
    ]
    rows.append(
        [
            "all",
            str(totals["items"]),
            *(cell(_method(totals, method)["extractable"], totals["items"]) for method in methods),
        ]
    )
    return rows


def _summary_rows(totals: dict[str, Any], methods: list[str]) -> list[list[str]]:
    documents = totals["documents"]
    return [
        [
            "documents with nothing extractable",
            *(f"{_method(totals, method)['clean_documents']}/{documents}" for method in methods),
        ],
        [
            "documents the leak check flags",
            *(f"{_method(totals, method)['documents_flagged']}/{documents}" for method in methods),
        ],
        [
            "copies the leak check refused",
            *(f"{_method(totals, method)['refused']}/{documents}" for method in methods),
        ],
    ]


def _method(totals: dict[str, Any], method: str) -> dict[str, Any]:
    return totals["methods"][method]


def _carrier_order(carrier: str) -> tuple[int, str]:
    return (CARRIERS.index(carrier) if carrier in CARRIERS else len(CARRIERS), carrier)


def _escape(text: str) -> str:
    return text.replace("_", "\\_")


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    return [
        "| " + " | ".join(header) + " |",
        "|" + "|".join("---" for _ in header) + "|",
        *("| " + " | ".join(row) + " |" for row in rows),
    ]
